#!/usr/bin/env node
// Collect every `--vf-*` custom property the library defines (in src/css and
// in component style objects) and write the list where tooling can read it:
//
//   tools/eslint-plugin-voidframe/rules/vf-token-names.ts   (committed; the
//       `no-unknown-vf-token` rule imports it)
//   dist/token-names.json                                   (with --dist; published
//       so consumers' own lints can read the registry)
//
// Usage: node scripts/export-token-names.mjs [--dist] [--check]
//   --check exits 1 when the committed TS list is stale instead of writing.
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = new Set(process.argv.slice(2));

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "__tests__" || name === "dist") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else yield full;
  }
}

export function collectTokenNames(root = repoRoot) {
  const names = new Set();
  for (const file of walk(join(root, "src", "css"))) {
    if (!file.endsWith(".css")) continue;
    for (const m of readFileSync(file, "utf8").matchAll(/(--vf-[\w-]+)\s*:/g)) names.add(m[1]);
  }
  for (const file of walk(join(root, "src"))) {
    if (!/\.(tsx?|mjs)$/.test(file)) continue;
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(/["'](--vf-[\w-]+)["']\s*(?:as\s+\w+\s*)?[:\]]/g)) names.add(m[1]);
    // Properties written imperatively: el.style.setProperty("--vf-x", …).
    for (const m of text.matchAll(/setProperty\(\s*["'](--vf-[\w-]+)["']/g)) names.add(m[1]);
  }
  return [...names].sort();
}

const names = collectTokenNames();
const tsPath = join(repoRoot, "tools/eslint-plugin-voidframe/rules/vf-token-names.ts");
const tsText =
  "// GENERATED by scripts/export-token-names.mjs — do not edit.\n" +
  "// Every --vf-* custom property defined in src/css or set from a component.\n" +
  "export const VF_TOKEN_NAMES: readonly string[] = [\n" +
  names.map((n) => `  ${JSON.stringify(n)},`).join("\n") +
  "\n];\n";

if (args.has("--check")) {
  const current = existsSync(tsPath) ? readFileSync(tsPath, "utf8") : "";
  if (current !== tsText) {
    console.error("[token-names] tools/eslint-plugin-voidframe/rules/vf-token-names.ts is stale; run `npm run tokens:names`.");
    process.exit(1);
  }
  console.log(`[token-names] up to date (${names.length} tokens)`);
} else {
  writeFileSync(tsPath, tsText);
  console.log(`[token-names] wrote ${names.length} names to ${tsPath}`);
}
if (args.has("--dist")) {
  mkdirSync(join(repoRoot, "dist"), { recursive: true });
  writeFileSync(join(repoRoot, "dist/token-names.json"), JSON.stringify({ tokens: names }, null, 2) + "\n");
  console.log("[token-names] wrote dist/token-names.json");
}
