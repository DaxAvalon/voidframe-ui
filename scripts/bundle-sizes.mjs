#!/usr/bin/env node
// Generate docs/bundle-sizes.md from dist/*.es.js gzipped sizes.
// Run after `npm run build`.

import { readFile, writeFile, readdir, stat } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const distDir = resolve(repoRoot, "dist");
const outFile = resolve(repoRoot, "docs/bundle-sizes.md");

const SUBPATHS = [
  ["voidframe.es.js", "(root) `voidframe-ui`"],
  ["primitives.es.js", "`voidframe-ui/primitives`"],
  ["core.es.js", "`voidframe-ui/core`"],
  ["layout.es.js", "`voidframe-ui/layout`"],
  ["navigation.es.js", "`voidframe-ui/navigation`"],
  ["forms.es.js", "`voidframe-ui/forms`"],
  ["data.es.js", "`voidframe-ui/data`"],
  ["activity.es.js", "`voidframe-ui/activity`"],
  ["overlays.es.js", "`voidframe-ui/overlays`"],
  ["media.es.js", "`voidframe-ui/media`"],
  ["animation.es.js", "`voidframe-ui/animation`"],
  ["icons.es.js", "`voidframe-ui/icons`"],
  ["chat.es.js", "`voidframe-ui/chat`"],
  ["specialty.es.js", "`voidframe-ui/specialty`"],
  ["interactive.es.js", "`voidframe-ui/interactive`"],
  ["charts.es.js", "`voidframe-ui/charts`"],
  ["dev.es.js", "`voidframe-ui/dev`"],
  ["tokens.es.js", "`voidframe-ui/tokens`"],
  ["testing.es.js", "`voidframe-ui/testing`"],
  ["voidframe.css", "`voidframe-ui/styles.css`"],
];

function fmt(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  return `${(bytes / 1024).toFixed(1)} KB`;
}

async function sizeOf(file) {
  const path = resolve(distDir, file);
  try {
    const buf = await readFile(path);
    const gz = gzipSync(buf, { level: 9 });
    return { raw: buf.length, gz: gz.length };
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

async function main() {
  const files = await readdir(distDir).catch(() => []);
  if (files.length === 0) {
    console.error(
      "dist/ is empty. Run `npm run build` before `node scripts/bundle-sizes.mjs`."
    );
    process.exit(1);
  }

  const rows = [];
  for (const [file, label] of SUBPATHS) {
    const s = await sizeOf(file);
    if (!s) continue;
    rows.push({ file, label, raw: s.raw, gz: s.gz });
  }

  const lines = [];
  lines.push("# Bundle sizes per subpath");
  lines.push("");
  lines.push(
    "Generated by `node scripts/bundle-sizes.mjs` after `npm run build`. " +
      "Sizes are the raw and gzip-9 compressed bytes of each ESM bundle file " +
      "in `dist/` — what your bundler will pull in for an `import` from each " +
      "subpath. Per-subpath ceilings are enforced by `npm run size`."
  );
  lines.push("");
  lines.push("| Subpath | Raw | Gzipped |");
  lines.push("| --- | ---: | ---: |");
  for (const r of rows) {
    lines.push(`| ${r.label} | ${fmt(r.raw)} | ${fmt(r.gz)} |`);
  }
  lines.push("");
  lines.push("> **Notes**");
  lines.push(">");
  lines.push(
    "> - The root `voidframe-ui` import is the legacy monolithic surface. " +
      "Bundler consumers (Vite / Webpack / Next.js / Remix) tree-shake it; " +
      "bundler-free consumers (Deno / Bun / esm.sh / unpkg / `node " +
      "--input-type=module`) should import from a category subpath instead."
  );
  lines.push(
    "> - Optional peers (`d3-*`, `dompurify`, `topojson-client`, `react-live`, " +
      "`jsbarcode`, `qrcode-generator`) are not included in any subpath's " +
      "bytes — they're declared as `peerDependenciesMeta.*.optional: true` " +
      "and resolved at the consumer."
  );
  lines.push(
    "> - The stylesheet is shipped once as `voidframe-ui/styles.css`; every " +
      "subpath consumes the same CSS file."
  );
  lines.push("");

  await writeFile(outFile, lines.join("\n"), "utf8");
  console.log(`Wrote ${outFile}`);
  for (const r of rows) {
    console.log(`  ${r.label.padEnd(40)} ${fmt(r.raw).padStart(10)}  gz ${fmt(r.gz).padStart(10)}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
